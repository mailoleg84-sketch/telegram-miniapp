_CYR = re.compile(r"[а-яё]+")


def _is_cyr(s: str) -> bool:
    return bool(s) and ("а" <= s[0] <= "я" or s[0] == "ё")


def _matches(word_en: str, ru_tokens: list[str], keys: tuple[str, ...]) -> bool:
    for key in keys:
        key = key.strip()
        if not key:
            continue
        if _is_cyr(key):
            for tok in ru_tokens:
                if tok.startswith(key):
                    return True
        else:
            if word_en == key or (word_en[-1:] == "s" and word_en[:-1] == key) \
                    or (word_en[-2:] == "es" and word_en[:-2] == key):
                return True
    return False


def classify_topic(word: str, translation: str, part_of_speech: str, original_topic: str = ""):
    """Каноническая тема (ключ CANONICAL_TOPICS) ИЛИ None, если не уверены.

    None => слово не попадает в тематическую колоду, остаётся в общем словаре."""
    w = " ".join(str(word or "").split()).lower()
    if w in _EXCLUDE:
        return None
    t = str(translation or "").lower()
    ru_tokens = _CYR.findall(t)
    orig = str(original_topic or "").lower()

    # 1) Доверяем надёжной исходной теме банка.
    if orig in _CLEAN_ORIGINAL:
        return _CLEAN_ORIGINAL[orig]

    # 2) Уверенное смысловое совпадение (русский корень по началу слова / англ. целиком).
    for topic, keys in _KEYWORDS:
        if _matches(w, ru_tokens, keys):
            return topic

    # 3) Уверенная часть речи -> Действия / Слова-описания.
    if part_of_speech in {"verb", "modal_verb"}:
        return "actions"
    if part_of_speech in {"adjective", "adverb"}:
        return "describe"

    # 4) Не уверены (абстрактные/служебные существительные) -> оставляем в словаре.
    return None
