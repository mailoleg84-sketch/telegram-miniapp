def flatten_extra_words() -> list[tuple[str, str, str, str]]:
    """Развёртка во плоский список (english, russian, topic, age_group).

    Внутренняя дедупликация: если одно и то же англ. слово встречается дважды,
    оставляем первое вхождение (стабильный порядок). Дедуп против основного банка
    делается в data/words.py при сборке LEARNING_WORDS."""
    seen: set[str] = set()
    out: list[tuple[str, str, str, str]] = []
    for wave in _WAVES:
        for topic, by_age in wave.items():
            for age_group, pairs in by_age.items():
                for english, russian in pairs:
                    key = " ".join(str(english or "").split()).lower()
                    if not key or " " in key or key in seen:
                        continue
                    seen.add(key)
                    out.append((english, russian, topic, age_group))
    return out
